SIZE = 256*1024


class EmbeddingScratchpadTop(LiteXModule):
    def __init__(self, width):
        self.unit = u = BonsaiEmbeddingScratchpad(input_width=width)
        self.scratchpad = sp = BonsaiScratchpad(SIZE)
        self.bus = sp.add_wishbone_port()
        self.cmd = stream.Endpoint(EMBEDDING_COMMAND)
        self.write_allow = Signal()
        # This owner exercises the production facade, not additional RAM ports.
        # Drain posted writes before accepting an operation. Sideband memory
        # reads/writes cannot borrow the ports while the client owns them.
        self.comb += [self.cmd.connect(u.cmd, omit={'valid', 'ready'}),
            u.cmd.valid.eq(self.cmd.valid & ~sp.sbw_pending),
            self.cmd.ready.eq(u.cmd.ready & ~sp.sbw_pending),
            sp.units_idle.eq(~u.busy), sp.sbw_gnt.eq(~u.busy),
            sp.fill.adr.eq(u.sp_rd_adr), u.sp_rd_dat.eq(sp.fill.dat_r),
            u.sp_wr_gnt.eq(self.write_allow), sp.gather.adr.eq(u.sp_wr_adr),
            sp.gather.dat_w.eq(u.sp_wr_dat),
            sp.gather.we.eq(Mux(u.sp_wr_req & u.sp_wr_gnt, u.sp_wr_we, 0))]


def vector(scales, codes, signs, *, error=0, overrides=None, src=0x4000,
           sign_base=0x8000, dst=0x10000):
    raw = qformats.ptq1_0_pack(scales, codes.reshape(-1, 128)).tobytes()
    groups = len(scales)
    if src == sign_base:
        # Read-only alias is legal. Interpret exactly the same bytes as signs;
        # don't inadvertently overwrite the compact source during setup.
        signs = np.unpackbits(np.frombuffer(raw[:groups*16], np.uint8), bitorder='little')
        signs = (1 - 2*signs.astype(np.int8)).astype(np.int8)
    sign_bytes = b''.join(packed(signs[g*128:(g+1)*128] < 0, 1).to_bytes(16, 'little')
                          for g in range(groups))
    command = dict(src=src, signs=sign_base, dst=dst, groups=groups,
                   protect_start=0, protect_end=0x1000)
    command.update(overrides or {})
    # Initialize output before inputs so aliasing cases retain valid input.
    writes = {dst+4*i: 0xdeadbeef for i in range(groups*128)}
    for base, payload in ((src, raw), (sign_base, sign_bytes)):
        writes.update({base+4*i: word for i, (word,) in enumerate(struct.iter_unpack('<I', payload))})
    for address in (src-4, src+len(raw), sign_base-4, sign_base+len(sign_bytes),
                    dst-4, dst+groups*512, 0, 0xffc):
        if 0 <= address < SIZE:
            writes.setdefault(address, 0xdeadbeef)
    assert all(0 <= address < SIZE and address % 4 == 0 for address in writes)
    checks = writes.copy()
    exponent = 0
    if not error:
        _, exponent, fp = golden(scales, codes, signs)
        checks.update({dst+4*i: int(value) for i, value in enumerate(fp.view(np.uint32))})
    header = [command[name] for name, _ in EMBEDDING_COMMAND]
    header += [error, exponent & 0xffffffff, groups*28//32+groups//2, groups*16,
               len(writes), len(checks)]
    return (struct.pack('<12I', *header) +
            b''.join(struct.pack('<II', address, value) for address, value in writes.items()) +
            b''.join(struct.pack('<II', address, value) for address, value in checks.items()))


@pytest.mark.parametrize('width', [16, 32])
def test_compiled_embedding_shared_scratchpad(tmp_path, width):
    verilator = shutil.which('verilator')
    if not verilator:
        pytest.skip('Verilator required for shared embedding qualification')
    examples, local_count = cases(width)
    vectors = []
    for scales, codes, signs, options in examples:
        if 'frame' in options or 'groups' in options:
            continue  # Physical scratchpad framing is generated by the owner.
        vectors.append(vector(scales, codes, signs, error=options.get('error', 0) << 8))
    # Exact in-place and partial overlap with either input, plus input/input
    # aliasing. A full row must be cached before the first output store.
    for src, sign_base, dst in ((0x4000, 0x8000, 0x4000), (0x4000, 0x8000, 0x8000),
                                (0x4000, 0x8000, 0x4020), (0x4000, 0x8000, 0x7fe0),
                                (0x4000, 0x4000, 0x10000), (0x4000, 0x4000, 0x4000)):
        vectors.append(vector(*example(40), src=src, sign_base=sign_base, dst=dst))
    for overrides, error in (({'groups': 0}, 1), ({'groups': 7}, 1), ({'groups': 65}, 1),
            ({'src': 1}, 1), ({'signs': 2}, 1), ({'dst': 31}, 5),
            ({'src': SIZE-32}, 2), ({'signs': SIZE-32}, 2), ({'dst': SIZE-32}, 2),
            ({'src': 0xffffe0}, 2), ({'signs': 0xffffe0}, 2), ({'dst': 0xffffe0}, 2),
            ({'groups': 65535}, 3), ({'protect_start': 32, 'protect_end': 0}, 1),
            ({'protect_end': SIZE+1}, 6),
            ({'protect_start': 0x10001, 'protect_end': 0x10002}, 4),
            ({'protect_start': 0x10fff, 'protect_end': 0x11000}, 4)):
        vectors.append(vector(*example(8), error=error, overrides=overrides))
    # Equality at the full-span bounds and at either protected interval edge.
    vectors += [vector(*example(8), src=SIZE-224, sign_base=SIZE-352,
                       overrides={'protect_start': 0x11000, 'protect_end': SIZE}),
                vector(*example(8), dst=SIZE-4096,
                       overrides={'protect_start': SIZE-4128, 'protect_end': SIZE-4096})]
    (tmp_path / 'vectors.bin').write_bytes(struct.pack('<II', 0x45535031, len(vectors))+b''.join(vectors))

    dut = EmbeddingScratchpadTop(width)
    u = dut.unit
    ports = {f'cmd_{name}': getattr(dut.cmd, name) for name, _ in EMBEDDING_COMMAND}
    ports.update(cmd_valid=dut.cmd.valid, cmd_ready=dut.cmd.ready, cancel=u.cancel,
        busy=u.busy, done=u.done, error=u.error, exponent=u.exponent,
        read_beats=u.read_beats, output_beats=u.output_beats, write_allow=dut.write_allow,
        rd_req=u.sp_rd_req, rd_adr=u.sp_rd_adr, wr_req=u.sp_wr_req, wr_adr=u.sp_wr_adr,
        wr_data=u.sp_wr_dat, wr_we=u.sp_wr_we)
    ports.update({f'host_{name}': getattr(dut.bus, name)
                  for name in ('cyc', 'stb', 'we', 'adr', 'dat_w', 'dat_r', 'sel', 'ack')})
    for name, signal in ports.items():
        signal.name_override = name
    rtl = tmp_path / 'embedding_sp.v'
    verilog.convert(dut, ios=set(ports.values()), name='embedding_sp').write(str(rtl))
    obj = tmp_path / 'obj'
    built = subprocess.run([verilator, '--cc', '--exe', '--build', '-j', '2', '-Wno-fatal',
        '--Mdir', str(obj), '--top-module', 'embedding_sp', str(rtl),
        str((Path(__file__).parent / 'rtl/embedding_sp.cpp').resolve())],
        capture_output=True, text=True, timeout=240)
    assert built.returncode == 0, built.stdout[-7000:]+built.stderr[-7000:]
    assert 'UNOPTFLAT' not in built.stderr, built.stderr
    run = subprocess.run([str(obj / 'Vembedding_sp')], cwd=tmp_path,
                         capture_output=True, text=True, timeout=120)
    assert run.returncode == 0, run.stdout+run.stderr
    assert 'EMBEDDING_SP_PASS' in run.stdout
    print(f'input_width={width} local_27b_rows={local_count}\n{run.stdout}')


def test_embedding_scratchpad_configuration_bounds():
    for size in (0, 31, 255, SIZE+32):
        with pytest.raises(ValueError):
            BonsaiEmbeddingScratchpad(size)


@pytest.mark.parametrize('width', [16, 32])
def test_embedding_scratchpad_combinational_graph_is_acyclic(width):
    # The basic Migen converter and functional Verilator tests can miss a
    # feedback loop that's dormant for valid inputs. Use the board's LiteX
    # dependency analysis too; no implicit timing-loop exception is acceptable.
    from litex.gen.fhdl import verilog as board_verilog
    dut = EmbeddingScratchpadTop(width)
    dut.clock_domains.cd_sys = ClockDomain('sys')
    with warnings.catch_warnings():
        warnings.filterwarnings('error', message='Combinatorial cycle detected.*')
        board_verilog.convert(dut, ios={dut.write_allow, dut.cd_sys.clk, dut.cd_sys.rst}, name='embedding_sp')
