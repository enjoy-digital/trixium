"""Python client for a running TriXium card.

Talks to the firmware console over the PCIe UART (/dev/ttyLXU0 through the liteuart driver,
or any tty the console is on), tokenizes on the host with the HuggingFace tokenizer, and
uses the firmware's chat protocol (`tokclr` / `tok <ids>` / `genb <n>`) so a conversation
continues on-card without resending history.

    from software.client import TriXium
    with TriXium() as b:
        b.hdrload()
        print(b.generate("The capital of France is", max_tokens=32))   # cap; ends at <|im_end|>
        for piece in b.stream("and Germany's?"):      # continues the conversation
            print(piece, end="", flush=True)
        print(b.command("stats"))

Requires pyserial and tokenizers (`pip install -e .` from the repository root).
"""

import os
import re
import json
import time
import fcntl

# Constants ----------------------------------------------------------------------------------------

DEFAULT_TTY       = "/dev/ttyLXU0"
DEFAULT_TOKENIZER = "models/1.7b/tokenizer.json"
PROMPT            = b"trixium> "
PBUF_TOKENS       = 2048  # On-card conversation buffer (firmware/main.c PBUF_N, = max_ctx).
LINE_MAX          = 850   # Firmware console line buffer is 1024 B; leave slack.
STATE_DIR         = "/tmp/trixium"  # Card state for trixium_smi (trixium_loader.h).

# TriXium Client -----------------------------------------------------------------------------------

class TriXiumError(RuntimeError):
    pass


class TriXium:
    def __init__(self, tty=DEFAULT_TTY, tokenizer=DEFAULT_TOKENIZER, chat_template=True,
                 timeout=600.0, temperature=0.0, top_p=1.0, repeat_penalty=1.0, seed=None,
                 system=None):
        """chat_template=False sends the text raw (completion style, like trixium_chat).
        temperature 0 = greedy (bit-exact, the default); repeat_penalty 1.1 alone already
        stops the list loops greedy decoding falls into."""
        # Optional dependencies, imported on use.
        import serial
        from tokenizers import Tokenizer
        self.ser = serial.Serial(tty, 115200, timeout=0.05)
        # One console session at a time (see tools/pcie_console.py): advisory lock on the tty.
        try:
            fcntl.flock(self.ser.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError:
            self.ser.close()
            raise TriXiumError(f"{tty} is in use by another console session (trixium_chat, "
                               "pcie_console.py, litex_term?) - close it first")
        self.tok           = Tokenizer.from_file(tokenizer)
        self.chat_template = chat_template
        self.system        = system  # A system turn ahead of the first user turn.
        self.timeout       = timeout
        self.turns         = 0       # Tokens currently in the on-card buffer.
        self.im_end        = self.tok.token_to_id("<|im_end|>") if chat_template else None
        self._closed       = True    # Did the last reply end with <|im_end|>?
        self.devnum        = int(re.sub(r"\D", "", tty) or 0)  # /dev/ttyLXU<n> -> card n.
        self.tokens        = 0       # Tokens generated by this session (trixium_smi).
        self._sync()
        if temperature or top_p != 1.0 or repeat_penalty != 1.0 or seed:
            self.set_sampling(temperature, top_p, repeat_penalty, seed)

    # Console --------------------------------------------------------------------------------------

    def close(self):
        self.ser.close()

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        self.close()

    def _sync(self):
        """Get to a fresh prompt: send an empty line, drain to the next `trixium> `."""
        self.ser.reset_input_buffer()
        self.ser.write(b"\n")
        self.ser.flush()
        self._read_until(PROMPT, timeout=30.0)

    def _read_until(self, needle, timeout, on_bytes=None):
        buf = bytearray()
        deadline = time.time() + timeout
        while time.time() < deadline:
            chunk = self.ser.read(4096)
            if chunk:
                buf += chunk
                if on_bytes:
                    on_bytes(chunk)
                if needle in buf:
                    return bytes(buf)
        raise TriXiumError(f"timeout waiting for {needle!r}; got {bytes(buf[-200:])!r}")

    # The firmware's UART RX ring is 128 bytes and its ISR drops bytes when it is full; the
    # console loop drains one byte per iteration and echoes each through a TX ring the host
    # driver empties on a poll timer. A long `tok` line written in one burst loses characters
    # (two ids merge into one past the vocabulary -> the engine fetches a row that does not
    # exist -> ENGSTALL, reconfigure the FPGA). So lines go out in chunks, each acknowledged by
    # its echo, byte for byte, before the next.
    PACE_CHUNK = 48

    def _write_paced(self, data):
        """Write `data`, waiting for each chunk's echo. Returns bytes read past the echo
        (the start of the reply, when a read overshoots)."""
        surplus = b""
        for i in range(0, len(data), self.PACE_CHUNK):
            chunk = data[i:i + self.PACE_CHUNK]
            self.ser.write(chunk)
            self.ser.flush()
            got = surplus
            deadline = time.time() + 3.0
            while len(got) < len(chunk) and time.time() < deadline:
                got += self.ser.read(len(chunk) - len(got))
            surplus = got[len(chunk):]
        return surplus

    def command(self, line, timeout=None):
        """Run one firmware console command; returns its output (without the echo/prompt)."""
        surplus = self._write_paced(line.encode() + b"\n")
        out = surplus + self._read_until(PROMPT, timeout or self.timeout)
        text = out.decode(errors="replace")
        return text.rsplit("trixium>", 1)[0].replace("\r", "").strip("\n")

    def hdrload(self):
        out = self.command("hdrload", timeout=60.0)
        if "inference ready" not in out:
            raise TriXiumError(f"hdrload did not report 'inference ready':\n{out}")
        return out

    def set_sampling(self, temperature=0.0, top_p=1.0, repeat_penalty=1.0, seed=None):
        """Firmware `sample` (values x1000): temperature 0 = greedy."""
        return self.command(f"sample {int(temperature*1000 + 0.5)} {int(top_p*1000 + 0.5)} "
                            f"{int(repeat_penalty*1000 + 0.5)} {seed or 0}")

    def stats(self, reset=False):
        return self.command("stats reset" if reset else "stats")

    # Generation -----------------------------------------------------------------------------------

    def reset(self):
        """Clear the on-card conversation."""
        self.command("tokclr")
        self.turns = 0
        self._closed = True

    def _encode(self, text):
        if self.chat_template:
            # Qwen3 chat turn; the empty <think> block asks for a direct answer (thinking
            # mode otherwise spends the whole budget inside <think>...</think>). On a
            # continuing conversation the previous reply is closed first: the card keeps
            # it in the buffer, and one cut short by max_tokens has no <|im_end|>.
            prefix = "" if self.turns == 0 else ("" if self._closed else "<|im_end|>") + "\n"
            if self.turns == 0 and self.system:
                prefix += f"<|im_start|>system\n{self.system}<|im_end|>\n"
            text = (f"{prefix}<|im_start|>user\n{text}<|im_end|>\n"
                    f"<|im_start|>assistant\n<think>\n\n</think>\n\n")
        return self.tok.encode(text).ids

    def _send_ids(self, ids):
        if self.turns + len(ids) > PBUF_TOKENS:
            raise TriXiumError(f"conversation would exceed the on-card buffer ({PBUF_TOKENS} "
                               "tokens); call reset()")
        i = 0
        while i < len(ids):
            line = "tok"
            while i < len(ids) and len(line) < LINE_MAX:
                line += f" {ids[i]}"
                i += 1
            out = self.command(line, timeout=10.0)
            m = re.search(r"TOK (\d+)", out)
            if not m:
                raise TriXiumError(f"tok not acknowledged: {out!r}")
        self.turns = int(m.group(1))

    def stream(self, text, max_tokens=256):
        """Append `text` to the conversation and yield decoded pieces as tokens arrive."""
        if self.turns == 0:
            self.command("tokclr")
        self._send_ids(self._encode(text))
        # The firmware stops at <|im_end|> (emitted, kept in the buffer) - without it the
        # model runs on past its answer until max_tokens.
        stop = f" {self.im_end}" if self.im_end is not None else ""
        self._state("generating")
        t0      = time.time()
        pending = self._write_paced(f"genb {max_tokens}{stop}\n".encode()).decode(errors="replace")
        ids          = []
        decoded_upto = 0
        deadline     = time.time() + self.timeout
        done         = False
        while not done and time.time() < deadline:
            chunk = self.ser.read(4096)
            if not chunk:
                continue
            pending += chunk.decode(errors="replace")
            if "GEN DONE" in pending:
                done = True
            # Token ids stream after "GEN:" as " %d" pieces. Take only digit runs that sit
            # between separators: a stray firmware message inside the stream must neither
            # contribute its numbers (e.g. "(14 descriptors)") as tokens nor hide the ids
            # that follow it.
            if "GEN:" in pending:
                seg = pending.split("GEN:", 1)[1].split("GEN DONE", 1)[0]
                ids = [int(t) for t in re.findall(r"(?:^|(?<=[ \r\n]))(\d+)(?=[ \r\n]|$)", seg)]
                # Decode incrementally; hold back the last id in case it is a partial UTF-8
                # sequence the next id completes.
                keep = len(ids) if done else max(0, len(ids) - 1)
                if keep > decoded_upto:
                    text_all = self.tok.decode(ids[:keep])
                    text_prev = self.tok.decode(ids[:decoded_upto]) if decoded_upto else ""
                    decoded_upto = keep
                    piece = text_all[len(text_prev):]
                    if piece:
                        yield piece
        if not done:
            raise TriXiumError("generation timed out")
        self.turns  += len(ids)
        self.tokens += len(ids)
        self._closed = bool(ids) and ids[-1] == self.im_end
        self._state("idle", tok_s=len(ids)/(time.time() - t0))
        if PROMPT.decode() not in pending.split("GEN DONE", 1)[1]:   # Usually in the same chunk.
            self._read_until(PROMPT, timeout=5.0)

    def _state(self, state, tok_s=0.0):
        """Record this session for trixium_smi (as trixium_loader.c's loader_state_write)."""
        record = {"pid": os.getpid(), "tool": "software.client", "state": state,
                  "tokens": self.tokens, "tok_s": round(tok_s, 3), "time": int(time.time())}
        path = os.path.join(STATE_DIR, f"trixium{self.devnum}.chat.json")
        try:
            os.makedirs(STATE_DIR, mode=0o777, exist_ok=True)
            with open(f"{path}.{os.getpid()}", "w", encoding="utf-8") as f:
                json.dump(record, f)
            os.replace(f"{path}.{os.getpid()}", path)
        except OSError:
            pass  # Best effort: the monitor is optional.

    def generate(self, text, max_tokens=256):
        """Append `text` to the conversation; return the generated text."""
        return "".join(self.stream(text, max_tokens))
